    private void configurarTabla() {
        DefaultTableModel modelo = new DefaultTableModel(
                new Object[]{"Identificacion", "Nombre", "Telefono"}, 0) {

            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
        tblClientes.setModel(modelo);
        tblClientes.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        tblClientes.setAutoCreateRowSorter(false);
    }

    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblClientes.getModel();
        modelo.setRowCount(0);
        for (Cliente c : DatosAplicacion.CLIENTES.obtenerTodos()) {
            modelo.addRow(new Object[]{
                c.getIdentificacion(), c.getNombre(), c.getTelefono()
            });
        }
    }

    private void LimpiarFormulario() {
        txtIdentificacion.setText("");
        txtNombre.setText("");
        txtTelefono.setText("");
        tblClientes.clearSelection();
        filaSeleccionada = -1;
        txtIdentificacion.requestFocus();
    }

    private boolean validarCampos() {
        if (txtIdentificacion.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese la identificación del cliente.");
            txtIdentificacion.requestFocus();
            return false;
        }
        if (txtNombre.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese el nombre del cliente.");
            txtNombre.requestFocus();
            return false;
        }
        if (txtTelefono.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese el teléfono del cliente.");
            txtTelefono.requestFocus();
            return false;
        }
        return true;
    }

    private Cliente obtenerDesdeControles() {
        return new Cliente(
                txtIdentificacion.getText().trim(),
                txtNombre.getText().trim(),
                txtTelefono.getText().trim());
    }

