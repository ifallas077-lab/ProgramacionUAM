    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if(!validarCampos()) return;
        
        Cliente nuevo = obtenerDesdeControles();
        
        for(Cliente c : DatosAplicacion.CLIENTES.obtenerTodos()){
            if(c.getIdentificacion().equals(nuevo.getIdentificacion())){
                JOptionPane.showMessageDialog(this, "Ya existe un cliente con esa identificacion");
                return;
            }
        }
        
        DatosAplicacion.CLIENTES.agregar(nuevo);
        cargarTabla();
        LimpiarFormulario();
        JOptionPane.showMessageDialog(this, "Cliente Guardado");
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (filaSeleccionada < 0){
            JOptionPane.showMessageDialog(this,"Seleccione un cliente de la tabla");
            return;
        }
        if(!validarCampos()) return;
        
        Cliente actual = DatosAplicacion.CLIENTES.obtener(filaSeleccionada);
        
        if(actual == null) {
            cargarTabla();
            LimpiarFormulario();
            return;
        }
        
        String nuevoID = txtIdentificacion.getText().trim();
        for (Cliente otro : DatosAplicacion.CLIENTES.obtenerTodos()){
            if(otro != actual && otro.getIdentificacion().equals(nuevoID)){
                JOptionPane.showMessageDialog(this," La identificacion ya pertenece a otro cliente");
                return;
            }
        }
        
        actual.setIdentificacion(nuevoID);
        actual.setNombre(txtNombre.getText().trim());
        actual.setTelefono(txtTelefono.getText().trim());
        
        cargarTabla();
        LimpiarFormulario();
        JOptionPane.showMessageDialog(this, "Cliente actualizado");
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void tblClientesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblClientesMouseClicked
        int vista = tblClientes.getSelectedRow();
        if(vista < 0 ) return;
        
        filaSeleccionada=tblClientes.convertRowIndexToModel(vista);
        
        Cliente elegido = DatosAplicacion.CLIENTES.obtener(filaSeleccionada);
        
        if(elegido == null) return;
        
        txtIdentificacion.setText(elegido.getIdentificacion());
        txtNombre.setText(elegido.getNombre());
        txtTelefono.setText(elegido.getTelefono());
    }//GEN-LAST:event_tblClientesMouseClicked

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (filaSeleccionada < 0){
            JOptionPane.showMessageDialog(this, "Seleccione un cliente de la tabla");
            return;
        }
        
        Cliente actual = DatosAplicacion.CLIENTES.obtener(filaSeleccionada);
        
        for (Mascota mascota : DatosAplicacion.MASCOTAS.obtenerTodos()) {
        if (mascota.getDuenio() == actual) {
            JOptionPane.showMessageDialog(this, "No se puede eliminar: Tiene mascotas asociadas");
            return;
        }
    }
        int respuesta = JOptionPane.showConfirmDialog(this, "Eliminar el cliente seleccionado? ", "Confirmacion",
                JOptionPane.YES_NO_OPTION);
        if (respuesta != JOptionPane.YES_OPTION) return;
        
        DatosAplicacion.CLIENTES.eliminar(filaSeleccionada);
        cargarTabla();
        LimpiarFormulario();
    }//GEN-LAST:event_btnEliminarActionPerformed

