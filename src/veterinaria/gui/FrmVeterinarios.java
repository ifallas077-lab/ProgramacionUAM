    private void tblVeterinariosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblVeterinariosMouseClicked
        int vista = tblVeterinarios.getSelectedRow();
        if(vista < 0 ) return;

        filaSeleccionada=tblVeterinarios.convertRowIndexToModel(vista);

        Veterinario elegido = DatosAplicacion.VETERINARIOS.obtener(filaSeleccionada);

        if(elegido == null) return;

        txtIdentificacion.setText(elegido.getCodigo());
        txtNombre.setText(elegido.getNombre());
        txtTelefono.setText(elegido.getEspecialidad());
    }//GEN-LAST:event_tblVeterinariosMouseClicked

