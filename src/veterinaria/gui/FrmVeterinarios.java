    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if(!validarCampos()) return;

        Veterinario nuevo = obtenerDesdeControles();

        for(Veterinario c : DatosAplicacion.VETERINARIOS.obtenerTodos()){
            if(c.getCodigo().equals(nuevo.getCodigo())){
                JOptionPane.showMessageDialog(this, "Ya existe un veterinario con ese código");
                return;
            }
        }

        DatosAplicacion.VETERINARIOS.agregar(nuevo);
        cargarTabla();
        LimpiarFormulario();
        JOptionPane.showMessageDialog(this, "Veterinario Guardado");
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (filaSeleccionada < 0){
            JOptionPane.showMessageDialog(this,"Seleccione un veterinario de la tabla");
            return;
        }
        if(!validarCampos()) return;

        Veterinario actual = DatosAplicacion.VETERINARIOS.obtener(filaSeleccionada);

        if(actual == null) {
            cargarTabla();
            LimpiarFormulario();
            return;
        }

        String nuevoID = txtIdentificacion.getText().trim();
        for (Veterinario otro : DatosAplicacion.VETERINARIOS.obtenerTodos()){
            if(otro != actual && otro.getCodigo().equals(nuevoID)){
                JOptionPane.showMessageDialog(this,"El código ya pertenece a otro veterinario");
                return;
            }
        }

        actual.setCodigo(nuevoID);
        actual.setNombre(txtNombre.getText().trim());
        actual.setEspecialidad(txtTelefono.getText().trim());

        cargarTabla();
        LimpiarFormulario();
        JOptionPane.showMessageDialog(this, "Veterinario actualizado");
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (filaSeleccionada < 0){
            JOptionPane.showMessageDialog(this, "Seleccione un veterinario de la tabla");
            return;
        }

        Veterinario actual = DatosAplicacion.VETERINARIOS.obtener(filaSeleccionada);

        for (Consulta consulta : DatosAplicacion.CONSULTAS.obtenerTodos()) {
            if (consulta.getVeterinario() == actual) {
                JOptionPane.showMessageDialog(this, "No se puede eliminar: tiene consultas asociadas");
                return;
            }
        }
        int respuesta = JOptionPane.showConfirmDialog(this, "Eliminar el veterinario seleccionado? ", "Confirmacion",
            JOptionPane.YES_NO_OPTION);
        if (respuesta != JOptionPane.YES_OPTION) return;

        DatosAplicacion.VETERINARIOS.eliminar(filaSeleccionada);
        cargarTabla();
        LimpiarFormulario();
    }//GEN-LAST:event_btnEliminarActionPerformed

