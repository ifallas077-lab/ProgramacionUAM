    private void configurarTabla() {
        DefaultTableModel modelo = new DefaultTableModel(
                new Object[]{"Código", "Nombre", "Especialidad"}, 0) {

            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
        tblVeterinarios.setModel(modelo);
        tblVeterinarios.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        tblVeterinarios.setAutoCreateRowSorter(false);
    }

    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblVeterinarios.getModel();
        modelo.setRowCount(0);
        for (Veterinario c : DatosAplicacion.VETERINARIOS.obtenerTodos()) {
            modelo.addRow(new Object[]{
                c.getCodigo(), c.getNombre(), c.getEspecialidad()
            });
        }
    }

    private void LimpiarFormulario() {
        txtIdentificacion.setText("");
        txtNombre.setText("");
        txtTelefono.setText("");
        tblVeterinarios.clearSelection();
        filaSeleccionada = -1;
        txtIdentificacion.requestFocus();
    }

    private boolean validarCampos() {
        if (txtIdentificacion.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese el código del veterinario.");
            txtIdentificacion.requestFocus();
            return false;
        }
        if (txtNombre.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese el nombre del veterinario.");
            txtNombre.requestFocus();
            return false;
        }
        if (txtTelefono.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese la especialidad del veterinario.");
            txtTelefono.requestFocus();
            return false;
        }
        return true;
    }

    private Veterinario obtenerDesdeControles() {
        return new Veterinario(
                txtIdentificacion.getText().trim(),
                txtTelefono.getText().trim(),
                txtNombre.getText().trim());
    }
