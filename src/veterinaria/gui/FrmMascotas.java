    private void cargarDuenios() {
        clientesDisponibles.clear();
        cmbDuenio.removeAllItems();
        for (Cliente c : DatosAplicacion.CLIENTES.obtenerTodos()) {
            clientesDisponibles.add(c);
            cmbDuenio.addItem(
                    c.getIdentificacion() + " - " + c.getNombre());
        }
        cmbDuenio.setSelectedIndex(-1);
    }

    private int buscarIndiceDuenio(Cliente buscado) {
        if (buscado == null) {
            return -1;
        }
        for (int i = 0; i < clientesDisponibles.size(); i++) {
            if (clientesDisponibles.get(i) == buscado) {
                return i;
            }
        }
        return -1;
    }

    private void configurarTabla() {
        DefaultTableModel modelo = new DefaultTableModel(
                new Object[]{"Nombre", "Especie", "Edad", "Peso", "Dueño"}, 0) {

            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
        tblMascotas.setModel(modelo);
        tblMascotas.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        tblMascotas.setAutoCreateRowSorter(false);
    }

    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblMascotas.getModel();
        modelo.setRowCount(0);
        for (Mascota c : DatosAplicacion.MASCOTAS.obtenerTodos()) {
            modelo.addRow(new Object[]{
                c.getNombre(), c.getEspecie(), c.getEdad(), c.getPeso(),
                c.getDuenio() == null ? "Sin dueño" : c.getDuenio()
            });
        }
    }

    private boolean validarCampos() {

        if (txtNombre.getText().trim().isEmpty()
                || txtEspecie.getText().trim().isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ingrese nombre y especie.");

            return false;

        }

        int pos = cmbDuenio.getSelectedIndex();

        if (pos < 0 || pos >= clientesDisponibles.size()) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Seleccione un dueño válido.");

            return false;

        }

        return true;

    }

    private Mascota obtenerDesdeControles() {

        Cliente duenio = clientesDisponibles.get(
                cmbDuenio.getSelectedIndex());

        int edad = ((Number) spnEdad.getValue()).intValue();

        double peso = ((Number) spnPeso.getValue()).doubleValue();

        return new Mascota(txtNombre.getText().trim(),
                txtEspecie.getText().trim(), edad, peso, duenio);

    }

    private void limpiarFormulario() {

        txtNombre.setText("");

        txtEspecie.setText("");

        spnEdad.setValue(0);

        spnPeso.setValue(0.1);

        cmbDuenio.setSelectedIndex(-1);

        tblMascotas.clearSelection();

        filaSeleccionada = -1;

        txtNombre.requestFocus();

    }

