    private void tblMascotasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMascotasMouseClicked
        int vista = tblMascotas.getSelectedRow();
        if (vista < 0) {
            return;
        }

        filaSeleccionada = tblMascotas.convertRowIndexToModel(vista);

        Mascota elegido = DatosAplicacion.MASCOTAS.obtener(filaSeleccionada);

        if (elegido == null) {
            return;
        }

        txtEspecie.setText(elegido.getEspecie());
        txtNombre.setText(elegido.getNombre());
        spnEdad.setValue(elegido.getEdad());
        spnPeso.setValue(elegido.getPeso());
        cmbDuenio.setSelectedIndex(buscarIndiceDuenio(elegido.getDuenio()));
    }//GEN-LAST:event_tblMascotasMouseClicked

