    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (filaSeleccionada < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione una mascota de la tabla");
            return;
        }
        if (!validarCampos()) {
            return;
        }
        Mascota actual = DatosAplicacion.MASCOTAS.obtener(filaSeleccionada);
        if (actual == null) {
            cargarTabla();
            limpiarFormulario();
            return;
        }
        Mascota datos = obtenerDesdeControles();
        actual.setNombre(datos.getNombre());
        actual.setEspecie(datos.getEspecie());
        actual.setEdad(datos.getEdad());
        actual.setPeso(datos.getPeso());
        actual.setDuenio(datos.getDuenio());
        cargarTabla();
        limpiarFormulario();
        JOptionPane.showMessageDialog(this, "Mascota actualizada");
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (filaSeleccionada < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione una mascota de la tabla");
            return;
        }

        Mascota actual = DatosAplicacion.MASCOTAS.obtener(filaSeleccionada);

        for (Consulta consulta : DatosAplicacion.CONSULTAS.obtenerTodos()) {
            if (consulta.getMascota() == actual) {
                JOptionPane.showMessageDialog(this, "No se puede eliminar: tiene consultas asociadas");
                return;
            }
        }
        int respuesta = JOptionPane.showConfirmDialog(this, "¿Eliminar la mascota seleccionada?", "Confirmacion",
                JOptionPane.YES_NO_OPTION);
        if (respuesta != JOptionPane.YES_OPTION) {
            return;
        }

        DatosAplicacion.MASCOTAS.eliminar(filaSeleccionada);
        cargarTabla();
        limpiarFormulario();
    }//GEN-LAST:event_btnEliminarActionPerformed

